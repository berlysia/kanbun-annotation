function getAttr(element: Element, name: string): string | null {
  return element.getAttribute(name);
}

/** 明示した id (`xml:id`、無ければ `id`。空の値は無いもの)。読む側と集める側が同じ規則を使うための唯一の入口 */
function readExplicitId(element: Element): string | null {
  return getAttr(element, 'xml:id') || getAttr(element, 'id') || null;
}

/** body は root の中のどの位置にあっても、本文を読む前に集める */
function collectBodyExplicitIds(root: Element, state: ParserState): void {
  for (const child of Array.from(root.childNodes)) {
    if (isElement(child) && getLocalName(child) === 'body') {
      for (const id of collectExplicitIds(child)) state.explicitIds.add(id);
    }
  }
}

const ID_BEARING_ELEMENTS: ReadonlySet<string> = new Set(['block', 'ref', 'br']);

/**
 * body の子孫から明示した id を集める。parser が読まない部分木 (知らない skam:* の中など) も含める。
 * 読む経路をここに複製すると経路が変わったときにずれて衝突が残るので、広い側に倒す (代わりに連番に欠番ができる)。
 * 深い入れ子でも落ちないよう、再帰でなく反復で列挙する
 */
function collectExplicitIds(body: Element): Set<string> {
  const ids = new Set<string>();
  const stack: Node[] = [body];
  while (stack.length > 0) {
    const node = stack.pop()!;
    for (const child of Array.from(node.childNodes)) {
      if (!isElement(child)) continue;
      if (ID_BEARING_ELEMENTS.has(getLocalName(child))) {
        const id = readExplicitId(child);
        if (id !== null) ids.add(id);
      }
      stack.push(child);
    }
  }
  return ids;
}

function getRequiredAttr(element: Element, name: string, elementName: string): string {
  // Note: @xmldom/xmldom returns "" for missing attributes, not null
  // We need to check hasAttribute to properly detect missing attributes
  if (!element.hasAttribute(name)) {
    throw parseErrorAt(element, `Missing required attribute '${name}' on <${elementName}>`);
  }
  const value = element.getAttribute(name);
  if (value === null || value === '') {
    throw parseErrorAt(element, `Missing required attribute '${name}' on <${elementName}>`);
  }
  return value;
}

function isElement(node: Node): node is Element {
  return node.nodeType === 1; // Node.ELEMENT_NODE
}

// CDATA は XML 上ただの文字データなので、TEXT_NODE と同じに扱う
function isText(node: Node): node is Text {
  return node.nodeType === 3 || node.nodeType === 4; // TEXT_NODE | CDATA_SECTION_NODE
}

function getLocalName(element: Element): string {
  return element.localName ?? element.nodeName.split(':').pop() ?? '';
}

